def get_icon(name: str, color: str = "#94A3B8", size: int = 16) -> QIcon:
    """Retrieve or generate a cached QIcon with 1.5px monochrome stroke.

    Args:
        name: Icon name from catalog.
        color: Stroke color hex code (default Slate 400 '#94A3B8').
        size: Target pixel size (default 16).

    Returns:
        QIcon instance.
    """
    key = (name, color, size)
    if key in _ICON_CACHE:
        return _ICON_CACHE[key]

    body = _ICON_SVGS.get(name)
    if not body:
        # Fallback to circle placeholder
        body = '<circle cx="12" cy="12" r="9"/>'

    svg_content = (
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{size}" height="{size}" '
        f'viewBox="0 0 24 24" fill="none" stroke="{color}" stroke-width="1.5" '
        f'stroke-linecap="round" stroke-linejoin="round">'
        f"{body}</svg>"
    )

    renderer = QSvgRenderer(QByteArray(svg_content.encode("utf-8")))
    pixmap = QPixmap(size, size)
    pixmap.fill(Qt.transparent)

    painter = QPainter(pixmap)
    renderer.render(painter)
    painter.end()

    icon = QIcon(pixmap)
    _ICON_CACHE[key] = icon
    return icon
